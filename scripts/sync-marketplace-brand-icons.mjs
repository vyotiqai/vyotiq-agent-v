/** The only colour in the kit. Consumers invert it for their dark theme. */
const GLYPH_INK = '#000000'
const TILE = 64
/**
 * Two boxes, because the sources are drawn to different conventions and a
 * single number would make one family look smaller than the other.
 *
 * Simple Icons and Font Awesome marks fill their viewBox edge to edge, so 40
 * of 64 is 40 of real ink. Phosphor draws inside a 256 box with roughly an
 * eighth of it as built-in padding, so 46 lands its ink at about 40 too.
 *
 * Both are wider than the old tile-bound 34: with no tile to sit inside, the
 * glyph can use the box, which matters at the 20px both consumers render.
 */
const BRAND_BOX = 40
const GLYPH_BOX = 46

export function iconFor(slug) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`
  const icon = simpleIcons[key]
  if (!icon) throw new Error(`simple-icons has no export ${key} (slug "${slug}")`)
  return icon
}

/** Centre a `src`-sized path inside `box` on the 64px canvas, keeping aspect. */
function placement(srcW, srcH, box) {
  const scale = box / Math.max(srcW, srcH)
  return {
    scale: scale.toFixed(6),
    x: ((TILE - srcW * scale) / 2).toFixed(4),
    y: ((TILE - srcH * scale) / 2).toFixed(4)
  }
}

function svgDoc(title, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${TILE}" height="${TILE}" viewBox="0 0 ${TILE} ${TILE}" fill="none">
  <title>${title}</title>
${body}
</svg>
`
}

/**
 * The one renderer. No tile, no background, no per-source colour: a single
 * black path, centred, that either consumer inverts for its dark theme.
 */
export function renderGlyph(title, pathData, srcW, srcH, box) {
  const { scale, x, y } = placement(srcW, srcH, box)
  return svgDoc(
    title,
    `  <g transform="translate(${x} ${y}) scale(${scale})">
    <path d="${pathData}" fill="${GLYPH_INK}"/>
  </g>`
  )
}

export function faMark(exportName) {
  const icon = faBrands[exportName]
  if (!icon) throw new Error(`@fortawesome/free-brands-svg-icons has no ${exportName}`)
  const [width, height, , , pathData] = icon.icon
  const d = Array.isArray(pathData) ? pathData.join('') : pathData
  return { title: icon.iconName, width, height, path: d }
}

export async function phosphorPath(name) {
  const svg = await readFile(phosphorAsset(name), 'utf8')
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`No path data in phosphor glyph "${name}"`)
  return paths.join(' ')
}

/** Build every icon this script owns, keyed by catalog id. */
export async function buildIcons() {
  const out = new Map()
  for (const [id, slug] of Object.entries(BRANDS)) {
    const icon = iconFor(slug)
    out.set(id, renderGlyph(icon.title, icon.path, 24, 24, BRAND_BOX))
  }
  for (const [id, exportName] of Object.entries(MARKS)) {
    const mark = faMark(exportName)
    out.set(id, renderGlyph(mark.title, mark.path, mark.width, mark.height, BRAND_BOX))
  }
  for (const [id, name] of Object.entries(GLYPHS)) {
    out.set(id, renderGlyph(name, await phosphorPath(name), 256, 256, GLYPH_BOX))
  }
  return out
}

async function main() {
  const catalog = JSON.parse(await readFile(catalogPath, 'utf8'))
  const byId = new Map(catalog.packages.map((p) => [p.id, p]))
  const icons = await buildIcons()

  /** Every id this script owns the catalog link for -> its icon file name. */
  const files = new Map([...icons.keys()].map((id) => [id, `${id}.svg`]))
  for (const [id, { file, source }] of Object.entries(VENDORED)) {
    if (!existsSync(path.join(iconsDir, file))) {
      throw new Error(`Vendored icon ${file} is missing. Re-download it from ${source}`)
    }
    files.set(id, file)
  }

  const unknown = [...files.keys()].filter((id) => !byId.has(id))
  if (unknown.length) throw new Error(`No catalog entry for: ${unknown.join(', ')}`)

  let linked = 0
  for (const [id, svg] of icons) await writeFile(path.join(iconsDir, `${id}.svg`), svg, 'utf8')
  for (const [id, file] of files) {
    if (byId.get(id).iconPath !== `icons/${file}`) linked += 1
  }

  // Rebuild each entry so a newly added `iconPath` lands where the existing
  // ones already sit instead of being appended after the connect metadata.
  catalog.packages = catalog.packages.map((entry) => {
    if (!files.has(entry.id)) return entry
    const relPath = `icons/${files.get(entry.id)}`
    const next = {}
    for (const [key, value] of Object.entries(entry)) {
      if (key === 'iconPath') continue
      if (key === 'installable') next.iconPath = relPath
      next[key] = value
    }
    if (!next.iconPath) next.iconPath = relPath
    return next
  })

  await writeFile(catalogPath, `${JSON.stringify(catalog, null, 2)}\n`, 'utf8')
  console.log(
    `[marketplace-icons] wrote ${icons.size} icons, kept ${Object.keys(VENDORED).length} vendored, linked ${linked} new catalog entries`
  )
}

// Keep the helpers importable for tests without running the sync.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}
